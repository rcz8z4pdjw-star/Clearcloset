"""
Report Generator.

Produces markdown reports, CSV exports, and data visualizations
for research analysis and manual trading decisions.

Report Types:
1. Daily Opportunity Report: Top opportunities ranked by score
2. Strategy Performance Report: Backtest results and analysis
3. Market Analysis Report: Deep dive on specific markets
4. Edge Summary Report: Overview of all detected edges
"""

import csv
import json
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any, Optional

from ..engine.data_ingestion.models import (
    Opportunity, BacktestResult, MarketSnapshot, Signal
)
from ..strategies.base import StrategyResult
from ..utils.config_loader import get_config
from ..utils.logging_setup import get_logger

logger = get_logger("report_generator")


class ReportGenerator:
    """
    Generates research reports and data exports.

    All reports are designed for manual review and decision-making.
    No automated trading actions are taken.
    """

    def __init__(self, output_dir: Optional[str] = None):
        """
        Initialize report generator.

        Args:
            output_dir: Base directory for output files
        """
        if output_dir:
            self.output_dir = Path(output_dir)
        else:
            self.output_dir = Path(get_config('reporting.daily_report.output_path', 'output/reports/'))

        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_daily_opportunity_report(
        self,
        opportunities: List[Opportunity],
        date: Optional[datetime] = None
    ) -> str:
        """
        Generate daily opportunity report in markdown format.

        Args:
            opportunities: Ranked opportunities to report
            date: Report date (default: today)

        Returns:
            Path to generated report file
        """
        date = date or datetime.utcnow()
        date_str = date.strftime("%Y-%m-%d")

        report_lines = [
            "# Daily Opportunity Report",
            f"**Date:** {date_str}",
            f"**Generated:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')} UTC",
            "",
            "---",
            "",
            "## IMPORTANT DISCLAIMER",
            "",
            "> This report is for **RESEARCH PURPOSES ONLY**.",
            "> No automated trading is performed.",
            "> All decisions must be made manually after careful review.",
            "> Past performance does not guarantee future results.",
            "> Prediction markets involve substantial risk of loss.",
            "",
            "---",
            "",
            "## Executive Summary",
            "",
            f"- **Total Opportunities Analyzed:** {len(opportunities)}",
            f"- **Top Opportunity Score:** {opportunities[0].composite_score:.3f}" if opportunities else "- No opportunities found",
            f"- **Average Expected Value:** {sum(o.expected_value for o in opportunities) / len(opportunities):.2%}" if opportunities else "",
            "",
            "---",
            "",
            "## Top Opportunities",
            "",
        ]

        # Top 10 detailed
        for i, opp in enumerate(opportunities[:10], 1):
            report_lines.extend(self._format_opportunity_detail(opp, i))
            report_lines.append("")

        # Summary table for all
        if len(opportunities) > 10:
            report_lines.extend([
                "---",
                "",
                "## Full Opportunity List",
                "",
                "| Rank | Market | Score | EV | Confidence | Side | Price |",
                "|------|--------|-------|-----|------------|------|-------|",
            ])

            for opp in opportunities:
                report_lines.append(
                    f"| {opp.rank} | {opp.market_name[:40]}... | {opp.composite_score:.3f} | "
                    f"{opp.expected_value:+.1%} | {opp.confidence:.0%} | {opp.suggested_side.upper()} | "
                    f"{opp.current_price:.1%} |"
                )

        # Footer
        report_lines.extend([
            "",
            "---",
            "",
            "## Methodology",
            "",
            "Opportunities are scored based on:",
            "- Expected Value (30%)",
            "- Confidence (20%)",
            "- Liquidity (15%)",
            "- Historical Edge Strength (15%)",
            "- Time Horizon (10%)",
            "- Risk Profile (10%)",
            "",
            "Signals are generated by multiple strategies including:",
            "- Liquidity vacuum detection",
            "- Favorite-longshot bias exploitation",
            "- Late resolution inefficiency",
            "- Cross-market arbitrage",
            "- Behavioral overreaction fading",
            "",
            "---",
            "",
            f"*Report generated by Prediction Market Research Platform v1.0*",
        ])

        # Write report
        report_path = self.output_dir / "daily" / f"opportunities_{date_str}.md"
        report_path.parent.mkdir(parents=True, exist_ok=True)

        with open(report_path, 'w') as f:
            f.write("\n".join(report_lines))

        logger.info(f"Daily report generated: {report_path}")
        return str(report_path)

    def _format_opportunity_detail(self, opp: Opportunity, rank: int) -> List[str]:
        """Format a single opportunity in detail."""
        lines = [
            f"### #{rank}: {opp.market_name[:60]}",
            "",
            f"**Market ID:** `{opp.market_id}`",
            f"**Source:** {opp.source.value.title()}",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Composite Score | **{opp.composite_score:.3f}** |",
            f"| Expected Value | **{opp.expected_value:+.2%}** |",
            f"| Confidence | {opp.confidence:.0%} |",
            f"| Current Price | {opp.current_price:.1%} |",
            f"| Suggested Side | **{opp.suggested_side.upper()}** |",
            f"| Suggested Size | {opp.suggested_size:.1%} of capital |",
            f"| Liquidity | ${opp.liquidity:,.0f} |",
            f"| Time to Resolution | {opp.hours_to_resolution:.0f}h |" if opp.hours_to_resolution else "| Time to Resolution | Unknown |",
            f"| Risk Score | {opp.risk_score:.2f} |",
            "",
            "**Key Factors:**",
        ]

        for factor in opp.key_factors[:3]:
            lines.append(f"- {factor}")

        lines.extend([
            "",
            "**Risks:**",
        ])

        for risk in opp.risks[:3]:
            lines.append(f"- {risk}")

        lines.extend([
            "",
            f"**Analysis:** {opp.explanation}",
        ])

        return lines

    def generate_strategy_performance_report(
        self,
        result: BacktestResult
    ) -> str:
        """
        Generate strategy performance report.

        Args:
            result: Backtest result to report

        Returns:
            Path to generated report file
        """
        report_lines = [
            f"# Strategy Performance Report: {result.strategy_name}",
            f"**Generated:** {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')} UTC",
            "",
            "---",
            "",
            "## Performance Summary",
            "",
            f"**Test Period:** {result.start_date.date()} to {result.end_date.date()}",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Total Trades | {result.total_trades} |",
            f"| Win Rate | {result.win_rate:.1%} |",
            f"| Total Return | **{result.total_return:+.2%}** |",
            f"| Annualized Return | {result.annualized_return:+.2%} |",
            f"| Sharpe Ratio | {result.sharpe_ratio:.2f} |",
            f"| Sortino Ratio | {result.sortino_ratio:.2f} |",
            f"| Max Drawdown | {result.max_drawdown:.2%} |",
            f"| Profit Factor | {result.profit_factor:.2f} |",
            "",
            "## Calibration Metrics",
            "",
            "| Metric | Value | Interpretation |",
            "|--------|-------|----------------|",
            f"| Brier Score | {result.brier_score:.4f} | {'Good' if result.brier_score < 0.20 else 'Fair' if result.brier_score < 0.25 else 'Poor'} |",
            f"| Calibration Error | {result.calibration_error:.4f} | {'Well-calibrated' if result.calibration_error < 0.05 else 'Moderately calibrated' if result.calibration_error < 0.10 else 'Poorly calibrated'} |",
            "",
            "## Trade Statistics",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Average Trade Duration | {result.avg_trade_duration_hours:.1f} hours |",
            f"| Average Profit (winning) | ${result.avg_profit_per_trade:.2f} |",
            f"| Average Loss (losing) | ${result.avg_loss_per_trade:.2f} |",
            f"| Best Trade | ${result.best_trade:.2f} |",
            f"| Worst Trade | ${result.worst_trade:.2f} |",
            f"| Max Consecutive Wins | {result.consecutive_wins} |",
            f"| Max Consecutive Losses | {result.consecutive_losses} |",
            "",
            "---",
            "",
            f"*Report generated by Prediction Market Research Platform v1.0*",
        ]

        report_path = self.output_dir / "strategy" / f"{result.strategy_name}_performance.md"
        report_path.parent.mkdir(parents=True, exist_ok=True)

        with open(report_path, 'w') as f:
            f.write("\n".join(report_lines))

        logger.info(f"Strategy report generated: {report_path}")
        return str(report_path)

    def export_opportunities_csv(
        self,
        opportunities: List[Opportunity],
        filename: Optional[str] = None
    ) -> str:
        """
        Export opportunities to CSV.

        Args:
            opportunities: Opportunities to export
            filename: Output filename

        Returns:
            Path to CSV file
        """
        if filename is None:
            filename = f"opportunities_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.csv"

        csv_path = self.output_dir / "csv_exports" / filename
        csv_path.parent.mkdir(parents=True, exist_ok=True)

        with open(csv_path, 'w', newline='') as f:
            writer = csv.writer(f)

            # Header
            writer.writerow([
                'rank', 'market_id', 'market_name', 'source',
                'composite_score', 'expected_value', 'confidence',
                'risk_score', 'current_price', 'liquidity',
                'hours_to_resolution', 'suggested_side', 'suggested_size',
                'signal_agreement', 'timestamp'
            ])

            # Data
            for opp in opportunities:
                writer.writerow([
                    opp.rank,
                    opp.market_id,
                    opp.market_name,
                    opp.source.value,
                    f"{opp.composite_score:.4f}",
                    f"{opp.expected_value:.4f}",
                    f"{opp.confidence:.4f}",
                    f"{opp.risk_score:.4f}",
                    f"{opp.current_price:.4f}",
                    f"{opp.liquidity:.2f}",
                    f"{opp.hours_to_resolution:.1f}" if opp.hours_to_resolution else "",
                    opp.suggested_side,
                    f"{opp.suggested_size:.4f}",
                    f"{opp.signal_agreement:.4f}",
                    opp.timestamp.isoformat()
                ])

        logger.info(f"CSV export: {csv_path}")
        return str(csv_path)

    def export_signals_json(
        self,
        signals: List[StrategyResult],
        filename: Optional[str] = None
    ) -> str:
        """
        Export signals to JSON.

        Args:
            signals: Signals to export
            filename: Output filename

        Returns:
            Path to JSON file
        """
        if filename is None:
            filename = f"signals_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.json"

        json_path = self.output_dir / "json_exports" / filename
        json_path.parent.mkdir(parents=True, exist_ok=True)

        data = []
        for signal in signals:
            data.append({
                'strategy_name': signal.strategy_name,
                'market_id': signal.market_id,
                'market_name': signal.market_name,
                'source': signal.source.value,
                'timestamp': signal.timestamp.isoformat(),
                'direction': signal.direction.value,
                'signal_strength': signal.signal_strength,
                'confidence': signal.confidence,
                'probability_estimate': signal.probability_estimate,
                'market_probability': signal.market_probability,
                'expected_value': signal.expected_value,
                'edge': signal.edge,
                'kelly_fraction': signal.kelly_fraction,
                'explanation': signal.explanation,
                'factors': signal.factors,
                'risks': signal.risks
            })

        with open(json_path, 'w') as f:
            json.dump(data, f, indent=2)

        logger.info(f"JSON export: {json_path}")
        return str(json_path)


def generate_daily_report(
    opportunities: List[Opportunity],
    output_dir: Optional[str] = None
) -> str:
    """Convenience function for daily report generation."""
    generator = ReportGenerator(output_dir)
    return generator.generate_daily_opportunity_report(opportunities)


def generate_strategy_report(
    result: BacktestResult,
    output_dir: Optional[str] = None
) -> str:
    """Convenience function for strategy report generation."""
    generator = ReportGenerator(output_dir)
    return generator.generate_strategy_performance_report(result)
